// Builds a self-hosted copy of the site's fonts (no Google Fonts in the app).
// Reads Fontsource packages from node_modules, keeps only the subsets the
// site needs, renames the families to the names the pages already use, and
// writes <out>/fonts/fonts.css plus the woff2 files.
import fs from "node:fs";
import path from "node:path";

const NM = "node_modules";

// [package css file, family name the pages use, subsets to keep]
const SOURCES = [
  ["@fontsource-variable/fraunces/opsz.css", "Fraunces", ["latin", "latin-ext"]],
  ["@fontsource-variable/inter/wght.css", "Inter", ["latin", "latin-ext"]],
  ["@fontsource-variable/jetbrains-mono/wght.css", "JetBrains Mono", ["latin"]],
  ["@fontsource/ibm-plex-mono/500.css", "IBM Plex Mono", ["latin"]],
  ["@fontsource/ibm-plex-mono/600.css", "IBM Plex Mono", ["latin"]],
  ...["400", "500", "600", "700"].map((w) => [
    `@fontsource/ibm-plex-sans-arabic/${w}.css`,
    "IBM Plex Sans Arabic",
    ["arabic", "latin"],
  ]),
];

export function buildFonts(outDir) {
  const fontDir = path.join(outDir, "fonts");
  fs.mkdirSync(fontDir, { recursive: true });
  const blocks = [];
  for (const [cssRel, family, subsets] of SOURCES) {
    const cssPath = path.join(NM, cssRel);
    const css = fs.readFileSync(cssPath, "utf8");
    const pkgDir = path.dirname(cssPath);
    for (const m of css.matchAll(/\/\*\s*([^*]+?)\s*\*\/\s*(@font-face\s*\{[^}]+\})/g)) {
      const block = m[2];
      if (/font-style:\s*italic/.test(block)) continue; // match Google's request (no italic axis)
      const file = (block.match(/url\(\.\/files\/([^)]+)\)/) || [])[1];
      if (!file) continue;
      // File names end in -<subset>-<weight|axis>-<style>.woff2, e.g. inter-latin-ext-wght-normal.woff2
      const sub = file.match(/-(latin-ext|latin|arabic|cyrillic-ext|cyrillic|greek-ext|greek|vietnamese|math|symbols)-[a-z0-9]+-(normal|italic)\.woff2$/);
      if (!sub || !subsets.includes(sub[1])) continue;
      fs.copyFileSync(path.join(pkgDir, "files", file), path.join(fontDir, file));
      blocks.push(
        block
          .replace(/font-family:\s*'[^']+'/, `font-family: '${family}'`)
          .replace(/url\(\.\/files\//, "url(/fonts/")
      );
    }
  }
  const header = "/* Self-hosted fonts (Fontsource, SIL Open Font License 1.1). Generated by app/fonts.mjs. */\n";
  fs.writeFileSync(path.join(fontDir, "fonts.css"), header + [...new Set(blocks)].join("\n") + "\n");
  return blocks.length;
}
